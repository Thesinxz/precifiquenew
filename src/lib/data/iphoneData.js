import { getSmartImage } from '../../data/smartAssets';

export const getProductImage = (modelName, colorName) => {
    const product = IPHONE_DATA.find(p => p.model.toLowerCase() === modelName?.toLowerCase());

    // 1. Try Manual Image from IPHONE_DATA
    if (product && product.colorImages && product.colorImages[colorName]) {
        const manualImg = product.colorImages[colorName];
        if (manualImg && manualImg.length > 0) return manualImg;
    }

    // 2. Fallback to Smart Asset (Apple)
    return getSmartImage(modelName, colorName);
};
